from typing import Protocol


class Broadcaster(Protocol):
    """Diffusion vers les navigateurs connectés (groupes : voir ``RealtimeGroups``)."""

    def observation_created(self, payload: dict) -> None: ...

    def observations_created(self, payloads: list[dict]) -> None: ...

    def climate_prediction_created(self, payload: dict) -> None: ...

    def weather_snapshot_created(self, payload: dict) -> None: ...

    def alerts_changed(self, payload: dict) -> None: ...

    def zones_changed(self, payload: list[dict]) -> None: ...
