from typing import Protocol


class DatabaseEventsPublisher(Protocol):
    """Faits persistés publiés pour les autres modules (topic ``database.events``)."""

    def observation_persisted(self, payload: dict) -> None: ...

    def climate_prediction_persisted(self, payload: dict) -> None: ...

    def weather_snapshot_persisted(self, payload: dict) -> None: ...

    def alerts_changed(self, zone_code=None) -> None: ...

    def zones_changed(self, zone_code=None) -> None: ...

    def alarm_rule_changed(self, *, rule, action, changed_fields) -> None: ...
